/**
  * @brief  This function handles Hard Fault exception.
  * @param  None
  * @retval None
  */
void HardFault_Handler(void)
{
  /* 罕见 CPU 异常(栈溢出/NULL 解引用/未对齐访问/总线坏访问)发生时,
   * 老实现 while(1){} 会让机器人永远死锁, 必须断电重启。
   * 改为软复位: 触发 SCB_AIRCR SYSRESETREQ, 等效冷启动, 所有外设/RAM 清零,
   * main 重新跑 ResetAll, 舵机回到 (100,80,90,90,0,180,0,180,100), 蓝牙重新可用。
   * 之所以 sane: 这条路径只在已经无法继续执行用户代码时被走到, 重启代价最低。 */
  NVIC_SystemReset();
}

/**
  * @brief  This function handles Memory Manage exception.
  * @param  None
  * @retval None
  */
void MemManage_Handler(void)
{
  /* 与 HardFault 同策略, 软复位代替死循环。F1 默认未使能 MPU, 这条路径几乎不会走,
   * 但留着无伤大雅, 任何时候卡住都比锁死强。 */
  NVIC_SystemReset();
}

/**
  * @brief  This function handles Bus Fault exception.
  * @param  None
  * @retval None
  */
void BusFault_Handler(void)
{
  /* 同 HardFault, 软复位代替死循环。 */
  NVIC_SystemReset();
}

/**
  * @brief  This function handles Usage Fault exception.
  * @param  None
  * @retval None
  */
void UsageFault_Handler(void)
{
  /* 同 HardFault, 软复位代替死循环。
   * F1 默认 SCB->CCR DIV_0_TRP/UNALIGN_TRP 未开, 这条几乎不触发, 留作兜底。 */
  NVIC_SystemReset();
}

